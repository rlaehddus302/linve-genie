    const { date } = await setupDay(page)
    await page.goto(`/settlements?date=${date}&rehearsal=true`)
    await expect(page.getByText('리허설 — 실제 정산이 아니에요')).toBeVisible()
    const summary = page.getByRole('region', { name: '정산 요약' })
    await expect(summary).toContainText('묶음 2개 · 미입금 2 · 부분 입금 0 · 입금 완료 0 · 과입금 0')
    await expect(summary).toContainText('38,000원') // 최종 합 14,000 + 24,000
    const list = page.getByRole('list', { name: '정산 묶음' })
    const card = list.getByRole('link', { name: /가나다/ })
    await expect(card).toContainText('상품 1개 · 10,000원')
    await expect(card).toContainText('배송비 4,000원')
    await expect(card).toContainText('최종 14,000원')
    await expect(card).toContainText('미입금')
    await card.click()
    const detail = page.getByRole('region', { name: '정산 자세히' })
    await expect(detail.getByRole('region', { name: '금액' })).toContainText('상품 합계 10,000원 + 배송비 4,000원 + 조정 0원 = 최종 14,000원')
