    const amount = pay.getByLabel('입금 금액')
    await expect(amount).toHaveValue('14000')
    await expect(pay).toContainText('입금 날짜는 적은 때로 남아요. 실제 입금일이 다르면 메모에 적어 주세요.')
    // 원 단위 금액 칸 (AC-S06-36)
    await amount.fill('14')
    await expect(pay.getByText('14원', { exact: true })).toBeVisible()
    await amount.fill('1만 4천')
    await expect(pay.getByText('14,000원', { exact: true })).toBeVisible()
    await amount.fill('만 사천 원')
    await expect(pay.getByText('14,000원', { exact: true })).toBeVisible()
    await amount.fill('abc')
    await expect(pay.getByText('금액을 14000처럼 적어 주세요.')).toBeVisible()
    await amount.fill('140000')
    await pay.getByRole('button', { name: '입금 적기' }).click()
