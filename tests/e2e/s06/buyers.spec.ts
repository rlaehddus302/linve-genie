import { test, expect, type Page } from '@playwright/test'
import { history, login, openNewBroadcast, postJson, registerApi, scopeView, smsApi, uniqueDate, viewerClaim, writeEvent } from './support.ts'

function uniq(prefix: string): string {
  return `${prefix}${String(Math.floor(Math.random() * 1e6))}`
}

async function setupMergeDay(page: Page): Promise<{ b: string; date: string; title: string; sms: string; hong: string }> {
  const date = uniqueDate()
  const title = uniq('합')
  const b = await openNewBroadcast(page, { date, rehearsal: true, title })
  await registerApi(page, b, 15, '핑크프릴', 10000)
  await registerApi(page, b, 16, '로즈', 5000)
  const reg = await writeEvent(page, { type: 'product.register', b, no: 18, name: '튤립', price: 8000, stock: 2 })
  expect(reg.status, JSON.stringify(reg.body)).toBeLessThan(300)
  await viewerClaim(page, b, '홍길동', '15', 'sim_hong_1111')
  await viewerClaim(page, b, '홍길동', '16', 'sim_hong_1111')
  await viewerClaim(page, b, '홍길동', '18', 'sim_hong_1111')
  await smsApi(page, { b, no: 18, memo: '김씨', phone: '010-3333-2468' })
  await smsApi(page, { b, no: 16, memo: '김씨', phone: '010-3333-2468' })
  const view = await scopeView(page, date, true)
  const sms = view.buyers.find((x) => x.kind === 'sms')!.id
  const hong = view.buyers.find((x) => x.kind === 'youtube' && x.display === '홍길동')!.id
  return { b, date, title, sms, hong }
}

