test('S9 AC-V2-07·09: "선버스" → 품종 확인 필요 + 후보 "선버스트" 단추, 누르면 채워지고 등록 뒤 새로 고쳐도 배운 이름 유지', async ({ page }) => {
  await setupV2(page)
  await sayAt(page, [['19번 선버스 팔천원', 0]])
  await page.clock.runFor(1800)
  const short = '19번 품종 미입력 8,000원'
  await expect(card(page, short).getByText('품종 확인 필요')).toBeVisible()
  const group = page.getByRole('group', { name: `${short} 품종 후보` })
  await expect(group.getByRole('button').first()).toHaveText('선버스트')
  await group.getByRole('button', { name: '선버스트', exact: true }).click()
  const chosen = card(page, '19번 선버스트 8,000원')
  await expect(chosen).toBeVisible()
  await cardButton(page, '19번 선버스트 8,000원', '등록').click()
  await expect(boardItem(page, 19)).toBeVisible()
  const learned = await page.evaluate((k) => window.localStorage.getItem(k), 'livejjim.voiceLearnedAliases')
  expect(learned).toContain('선버스트')
  // 새로 고침 뒤
  await page.clock.resume()
  await page.reload()
  await page.getByRole('button', { name: '음성 켜기', exact: true }).click()
  await expect(page.getByRole('region', { name: '음성 등록' }).getByRole('status').filter({ hasText: '음성: 듣는 중' })).toBeVisible()
  const now = await page.evaluate(() => Date.now())
  await page.clock.pauseAt(now + 3000)
  await sayAt(page, [['30번 선버스 팔천원', 0]])
  await page.clock.runFor(1800)
  await expect(card(page, '30번 선버스트 8,000원')).toBeVisible()
})

