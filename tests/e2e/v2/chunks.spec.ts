for (const [label, width, min] of [['PC', 1440, 28], ['휴대폰 375', 375, 22]] as const) {
  test(`AC-V2-17 ${label}: "들은 말" 칸에 모은 글·중간 결과, 글자 ${String(min)}px 이상, <b>는 글자로, 읽은 뒤 결과 줄`, async ({ page }) => {
    await setupV2(page, { width })
    await sayAt(page, [['십오번', 0], ['<b>엘레강스</b>', 300, false]])
    const box = heardBox(page)
    await expect(box).toContainText('십오번')
    await expect(box).toContainText('<b>엘레강스</b>')
    await expect(box.locator('b')).toHaveCount(0)
    const size = await box.getByText('십오번').evaluate((el) => parseFloat(getComputedStyle(el).fontSize))
    expect(size).toBeGreaterThanOrEqual(min)
    await sayAt(page, [['엘레강스 이만원', 300]])
    await page.clock.runFor(1800)
    await expect(box.getByRole('status')).toHaveText('15번 · 엘레강스 · 20,000원')
    await expect(card(page, '15번 엘레강스 20,000원')).toBeVisible()
    for (const word of ['HIGH', 'LOW', 'final']) await expect(page.getByText(word, { exact: false })).toHaveCount(0)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
    expect(overflow).toBe(false)
  })
}

