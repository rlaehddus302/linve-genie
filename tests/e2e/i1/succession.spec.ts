// AC-I1-71·33·32 (승계·버릴 라벨·재출력 필요·Alt+P) — PC가 출력 기기(시험용 프린터), 휴대폰은 보기만.
import { expect, test } from '@playwright/test'
import { boardItem, cleanupPrint, history, login, postJson, printOverview, realBroadcast, registerApi, scopeLabels, setBehavior, smsApi, uniqueDate, waitPrinted, writeEvent, becomeDevice } from './support.ts'

test.afterEach(async ({ page }) => {
  await cleanupPrint(page)
})

test('AC-I1-71: 승계 → 새 라벨 자동 출력·버릴 라벨 두 기기·버렸어요·품종 고침 → 재출력 필요 → Alt+P', async ({ page, browser }) => {
  const date = uniqueDate()
  await login(page)
  const b = await realBroadcast(page, date)
  await becomeDevice(page, 'PC')
  await page.goBack()
  await registerApi(page, b, 15, '핑크프릴', 14000)
  await expect(boardItem(page, 15)).toBeVisible()
  await smsApi(page, { b, no: 15, phone: '010-1111-2222' })
  await smsApi(page, { b, no: 15, phone: '010-3333-4444' })
  await waitPrinted(page, 1)
  await expect(boardItem(page, 15)).toContainText('라벨 출력됨')

  // 휴대폰 (같은 계정, 다른 컨텍스트)
  const phoneCtx = await browser.newContext({ viewport: { width: 375, height: 812 }, locale: 'ko-KR', timezoneId: 'Asia/Seoul', baseURL: new URL(page.url()).origin })
  const phone = await phoneCtx.newPage()
  try {
    await login(phone)
    await phone.goto(`/broadcasts/${encodeURIComponent(b)}`)
    await expect(boardItem(phone, 15)).toContainText('라벨 출력됨')

    const day = await (await page.request.get(`/api/days/${date}`)).json() as { claims: { id: string; buyer: string; no: number; status: string }[] }
    const first = day.claims.filter((c) => c.no === 15)[0]!
    const res = await writeEvent(page, { type: 'host.cancel', b, no: 15, buyer: first.buyer, reason: '시험' })
    expect(res.status, JSON.stringify(res.body)).toBeLessThan(300)

    await waitPrinted(page, 2)
    const alerts = (p: typeof page) => p.getByRole('region', { name: '알림' })
    await expect(alerts(page)).toContainText('버릴 라벨 1')
    await expect(alerts(phone)).toContainText('버릴 라벨 1')
    await expect(boardItem(page, 15)).toContainText('라벨 출력됨')
    const ov = await printOverview(page)
    expect(ov.discard).toHaveLength(1)
    expect(ov.discard[0]!.word).toBe('폐기 — 버려 주세요')

    // 휴대폰에서 버렸어요 → 두 기기 모두 사라짐
    await alerts(phone).getByRole('button', { name: /버릴 라벨 1/ }).click()
    const dlg = phone.getByRole('dialog', { name: '버릴 라벨' })
    await expect(dlg).toBeVisible()
    await dlg.getByRole('button', { name: /버렸어요/ }).first().click()
    await expect(alerts(phone)).not.toContainText('버릴 라벨')
    await expect(alerts(page)).not.toContainText('버릴 라벨')

    // 품종 고침 → 재출력 필요 → Alt+P → 1 → 라벨 출력됨(2번)
    const upd = await writeEvent(page, { type: 'product.update', b, no: 15, name: '핑크프릴 대품' })
    expect(upd.status, JSON.stringify(upd.body)).toBeLessThan(300)
    await expect(boardItem(page, 15)).toContainText('재출력 필요')
    await expect(boardItem(phone, 15)).toContainText('재출력 필요')
    await page.getByLabel('빠른 입력').fill('15번')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog', { name: '15번 자세히' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('빠른 입력')).toBeFocused()
    await page.keyboard.press('Alt+KeyP')
    const re = page.getByRole('dialog', { name: '라벨 다시 출력' })
    await expect(re).toBeVisible()
    await expect(re).toContainText('15번 라벨을 다시 출력할까요?')
    await expect(re.getByRole('button', { name: '닫기' })).toBeFocused()
    await page.keyboard.press('1')
    await waitPrinted(page, 3)
    await expect(boardItem(page, 15)).toContainText('라벨 출력됨')
    await expect(boardItem(phone, 15)).toContainText('라벨 출력됨')
    await expect(re.getByRole('status')).toHaveText('다시 출력을 접수했어요.')
    await page.keyboard.press('Escape')
    await expect(re).toHaveCount(0)
    await expect(page.getByLabel('빠른 입력')).toBeFocused()
    await expect(page.getByLabel('빠른 입력')).toHaveValue('')
    const labels = await scopeLabels(page, date)
    const winner = labels.find((l) => l.winner && l.no === 15)!
    expect(winner.printed).toBe(2)
    expect(winner.data?.['name']).toBe('핑크프릴 대품')

    // 출력 중(지연)에 그 1등 취소 → 나온 뒤 버릴 라벨
    await setBehavior(page, 4, { delayMs: 3000 })
    const second = day.claims.filter((c) => c.no === 15)[1]!
    await page.keyboard.press('Alt+KeyP')
    await expect(re).toBeVisible()
    await page.keyboard.press('1')
    await expect.poll(async () => (await printOverview(page)).queue.printing).toBe(1)
    const res2 = await writeEvent(page, { type: 'host.cancel', b, no: 15, buyer: second.buyer, reason: '시험' })
    expect(res2.status, JSON.stringify(res2.body)).toBeLessThan(300)
    await waitPrinted(page, 4)
    // B 라벨 키의 출력함 작업 셋(자동·다시 출력·지연 중 다시 출력)이 모두 "폐기 — 버려 주세요"(AC-I1-05: 출력함 작업마다)
    await expect(alerts(page)).toContainText('버릴 라벨 3')
    await expect(alerts(phone)).toContainText('버릴 라벨 3')
    const events = await history(page, date, false)
    expect(events.filter((e) => e.type === 'effect.labelPrinted')).toHaveLength(2)
  } finally {
    await phoneCtx.close()
  }
})

test('AC-I1-31: 상품 자세히 — 새 1등 라벨(미리 보기·이력·다시 출력)과 지난 1등의 폐기 라벨("폐기 — 버려 주세요" → 버렸어요 → "폐기")', async ({ page }) => {
  const date = uniqueDate()
  await login(page)
  const b = await realBroadcast(page, date)
  await becomeDevice(page, 'PC')
  await page.goBack()
  await registerApi(page, b, 15, '핑크프릴', 14000)
  await smsApi(page, { b, no: 15, phone: '010-2020-0001' })
  await smsApi(page, { b, no: 15, phone: '010-2020-0002' })
  await waitPrinted(page, 1)
  const day = await (await page.request.get(`/api/days/${date}`)).json() as { claims: { buyer: string; no: number }[] }
  const res = await writeEvent(page, { type: 'host.cancel', b, no: 15, buyer: day.claims[0]!.buyer, reason: '시험' })
  expect(res.status).toBeLessThan(300)
  await waitPrinted(page, 2)
  await boardItem(page, 15).click()
  const detail = page.getByRole('dialog', { name: '15번 자세히' })
  const labels = detail.getByRole('region', { name: '라벨' })
  const group = labels.getByRole('group', { name: /^1등 .+ 라벨$/ })
  await expect(group).toHaveCount(1)
  await expect(group).toContainText('라벨 출력됨')
  await expect(group).toContainText(/1번 출력 · \d\d:\d\d PC/)
  await expect(group.getByRole('button', { name: '다시 출력' })).toBeVisible()
  await expect(group.getByRole('button', { name: '라벨 출력' })).toHaveCount(0)
  const voided = labels.getByRole('list', { name: '폐기한 라벨' })
  await expect(voided).toContainText('지난 1등 라벨 · 문자찜 · 폐기 — 버려 주세요')
  const ov = await printOverview(page)
  await postJson(page, '/api/print/jobs/discard', { date, id: ov.discard[0]!.id })
  await expect(voided).toContainText('지난 1등 라벨 · 문자찜 · 폐기')
  await expect(voided).not.toContainText('버려 주세요')
})

test('AC-I1-05·12: 번호 변경 → 출력한 라벨은 버릴 라벨, 대기 라벨은 출력 안 함 · 가격 변경(입금 전 찜에 적용) → 재출력 필요, 새 찜에만이면 아님 · 재고 늘림 → 대기자 새 라벨', async ({ page }) => {
  const date = uniqueDate()
  await login(page)
  const b = await realBroadcast(page, date)
  await becomeDevice(page, 'PC')
  await page.goBack()
  await registerApi(page, b, 15, '핑크프릴', 14000)
  await registerApi(page, b, 16, '청보석', 9000)
  await smsApi(page, { b, no: 15, phone: '010-3030-0001' })
  await smsApi(page, { b, no: 15, phone: '010-3030-0002' })
  await smsApi(page, { b, no: 16, phone: '010-3030-0003' })
  await waitPrinted(page, 2)
  // 가격: 새 찜에만 → 재출력 필요 아님
  let r = await writeEvent(page, { type: 'product.update', b, no: 16, price: 9500, applyTo: 'NEW_ONLY' })
  expect(r.status, JSON.stringify(r.body)).toBeLessThan(300)
  await expect(boardItem(page, 16)).toContainText('라벨 출력됨')
  // 가격: 입금 전 찜에도 → 재출력 필요
  r = await writeEvent(page, { type: 'product.update', b, no: 16, price: 9900, applyTo: 'UNPAID_CLAIMS' })
  expect(r.status, JSON.stringify(r.body)).toBeLessThan(300)
  await expect(boardItem(page, 16)).toContainText('재출력 필요')
  // 재고 늘림 → 15번 대기자가 확정 → 새 라벨 자동 출력
  r = await writeEvent(page, { type: 'product.update', b, no: 15, stock: 2 })
  expect(r.status, JSON.stringify(r.body)).toBeLessThan(300)
  await waitPrinted(page, 3)
  // 멈추고 16번에 다시 출력 대기 → 번호 변경 16 → 26
  await postJson(page, '/api/print/pause', {})
  const labels = await scopeLabels(page, date)
  const l16 = labels.find((l) => l.no === 16 && l.winner)!
  r = await postJson(page, '/api/print/labels/reprint', { requestId: crypto.randomUUID(), b, claim: l16.claim, version: l16.version })
  expect(r.status, JSON.stringify(r.body)).toBe(200)
  await expect(boardItem(page, 16)).toContainText('라벨 대기')
  r = await writeEvent(page, { type: 'product.renumber', b, from: 16, to: 26 })
  expect(r.status, JSON.stringify(r.body)).toBeLessThan(300)
  const ov = await printOverview(page)
  expect(ov.queue.waiting).toBe(0)
  // 16번(지금 26번)으로 출력한 라벨 한 장이 버릴 라벨, 대기 중이던 다시 출력은 버릴 라벨이 아니다
  expect(ov.discard).toHaveLength(1)
  expect(ov.discard[0]!.label.no).toBe(16)
  await expect(page.getByRole('region', { name: '알림' })).toContainText('버릴 라벨 1')
  // Alt+1 순서: 출력 멈춤 → 버릴 라벨 (AC-I1-32)
  await page.getByLabel('빠른 입력').focus()
  await page.keyboard.press('Alt+1')
  await expect(page.getByRole('dialog', { name: '출력 멈춤' })).toBeVisible()
  await page.keyboard.press('Escape')
  await postJson(page, '/api/print/restart', {})
  await expect(page.getByRole('region', { name: '알림' })).not.toContainText('출력 멈춤')
  await page.keyboard.press('Alt+1')
  await expect(page.getByRole('dialog', { name: '버릴 라벨' })).toBeVisible()
  await page.keyboard.press('Escape')
})
