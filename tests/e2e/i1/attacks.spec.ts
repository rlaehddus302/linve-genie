  await login(page)
  const b = await realBroadcast(page, date)
  await becomeDevice(page, 'PC')
  await setBehavior(page, 1, { delayMs: 3000 })
  await registerApi(page, b, 1, '품종1', 5000)
  await smsApi(page, { b, no: 1 })
  const printer = region(page, '프린터')
