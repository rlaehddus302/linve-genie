async function queueCancelOfWinner(page: Page, no: number, nick: string, reason = '시청자 요청'): Promise<void> {
  await boardItem(page, no).click()
  await page.getByRole('dialog', { name: `${String(no)}번 자세히` }).getByRole('region', { name: '1등' }).getByRole('button', { name: '취소' }).click()
  const dlg = page.getByRole('dialog', { name: `${String(no)}번 ${nick} 취소` })
  await dlg.getByLabel('사유').fill(reason)
  await dlg.getByLabel('사유').press('Enter')
}

