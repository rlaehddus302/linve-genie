test('AC-S05-02: 제목을 비우면 서버 기본 "N부", 날짜 기본 오늘(KST), 목록은 날짜 최근 순·리허설 글자', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: '새 방송 시작' }).click()
  await expect(page.getByLabel('날짜')).toHaveValue(todayKst())
  await page.getByLabel('제목').fill('')
  await page.getByRole('button', { name: '이 방송 시작하기' }).click()
  await expect(page.getByLabel('빠른 입력')).toBeFocused()
  await expect(page.getByRole('heading', { level: 1 })).toContainText(/\d+부/)
  const oldTitle = `아주 옛 리허설 ${String(Date.now() % 1_000_000)}`
  await openNewBroadcast(page, { date: '2004-01-01', rehearsal: true, title: oldTitle })
  await page.getByRole('link', { name: '방송 목록' }).click()
  const links = page.getByRole('list', { name: '방송' }).getByRole('link')
  await expect(links.first()).toBeVisible()
  const texts = await links.allInnerTexts()
  const old = texts.findIndex((t) => t.includes(oldTitle))
  expect(old).toBeGreaterThanOrEqual(0)
  expect(texts[old]).toContain('리허설')
  // 그보다 뒤에는 같은 날짜(2004-01-01)의 방송만 온다
  for (const t of texts.slice(old + 1)) expect(t).toMatch(/2004|1월 1일/)
})

test('AC-S05-21: 위로 올려 보는 중이면 자리를 지키고 "새 메시지 n개", 누르면 맨 아래', async ({ page }) => {
  await login(page)
  const b = await openNewBroadcast(page, { date: uniqueDate(), rehearsal: true })
  for (let i = 0; i < 40; i += 1) await sendViewerChat(page, b, `손님${String(i)}`, `안녕하세요 ${String(i)}`)
  const list = page.getByRole('list', { name: '채팅 메시지' })
  await expect(list).toContainText('안녕하세요 39')
  await list.evaluate((el) => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')) })
  const before = await list.evaluate((el) => el.scrollTop)
  await sendViewerChat(page, b, '새손님', '새 글 하나')
  await sendViewerChat(page, b, '새손님', '새 글 둘')
  await expect(page.getByRole('button', { name: '새 메시지 2개' })).toBeVisible()
  expect(await list.evaluate((el) => el.scrollTop)).toBe(before)
  await page.getByRole('button', { name: '새 메시지 2개' }).click()
  await expect(page.getByRole('button', { name: /새 메시지/ })).toHaveCount(0)
  expect(await list.evaluate((el) => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThanOrEqual(30)
})

test('AC-S05-21: 처음엔 최근 메시지만, "이전 메시지 보기"로 더 받는다', async ({ page }) => {
  await login(page)
  const date = uniqueDate()
  const b = await openNewBroadcast(page, { date, rehearsal: true })
  const started = await postJson(page, `/api/broadcasts/${b}/rehearsal/generator/start`, { total: 300, perSecond: 50, seed: 3 })
  expect(started.status).toBe(200)
  await expect.poll(async () => ((await (await page.request.get(`/api/broadcasts/${b}/rehearsal/generator`)).json()) as { generator: { running: boolean } }).generator.running, { timeout: 30_000 }).toBe(false)
  await page.reload()
  const list = page.getByRole('list', { name: '채팅 메시지' })
  await expect(page.getByRole('button', { name: '이전 메시지 보기' })).toBeVisible()
  const first = await list.getByRole('listitem').count()
  expect(first).toBeLessThan(300)
  await page.getByRole('button', { name: '이전 메시지 보기' }).click()
  await expect.poll(() => list.getByRole('listitem').count()).toBeGreaterThan(first)
})

test('AC-S05-22: 언급에 없는 번호는 번호 칸으로, 이미 바꾼 번호는 "바꿈"으로 고를 수 없다, 결과가 메시지 옆에', async ({ page }) => {
  await login(page)
  const date = uniqueDate()
  const b = await openNewBroadcast(page, { date, rehearsal: true })
  await register(page, '15 핑크프릴 10000', 15)
  await sendViewerChat(page, b, '수사', '십오번이요')
  const row = page.getByRole('list', { name: '채팅 메시지' }).getByRole('listitem').filter({ hasText: '십오번이요' })
  // 잡담 줄(언급 아님)은 줄을 눌러야 버튼이 보인다 (AC-UX2-03)
  await row.getByText('십오번이요').click()
  await row.getByRole('button', { name: '찜으로 바꾸기' }).click()
  const dlg = page.getByRole('dialog', { name: '메시지를 찜으로 바꾸기' })
  await dlg.getByLabel('번호').fill('15')
  await dlg.getByRole('button', { name: '바꾸기' }).click()
  await expect(row).toContainText(/초 뒤 보내요/)
  await expect(row).toContainText('15번 1등', { timeout: 15_000 })
  await expect(boardItem(page, 15)).toContainText('수사')
  // 마우스를 올리면 보인다 (AC-UX2-04, PC)
  await row.hover()
  await row.getByRole('button', { name: '찜으로 바꾸기' }).click()
  const dlg2 = page.getByRole('dialog', { name: '메시지를 찜으로 바꾸기' })
  await dlg2.getByLabel('번호').fill('15')
  await dlg2.getByRole('button', { name: '바꾸기' }).click()
  await expect(dlg2).toContainText('15번으로는 이미 바꿨어요.')
  expect((await history(page, date, true)).filter((e) => e.type === 'host.convertMessage')).toHaveLength(1)
})

