test('AC-S05-10: 응답 전에는 "등록하는 중…"만 — 보드에 미리 나타나지 않는다', async ({ page }) => {
  await login(page)
  await openNewBroadcast(page, { date: uniqueDate(), rehearsal: false })
  let release: () => void = () => undefined
  const gate = new Promise<void>((r) => { release = r })
  await page.route('**/api/events**', async (route) => {
    await gate
    await route.continue()
  })
  const input = page.getByLabel('빠른 입력')
  await input.fill('15 핑크프릴 10000')
  await input.press('Enter')
  await expect(page.getByText('등록하는 중…')).toBeVisible()
  await expect(boardItem(page, 15)).toHaveCount(0)
  await expect(page.getByText('15번을 등록했어요')).toHaveCount(0)
  release()
  await expect(boardItem(page, 15)).toBeVisible()
  await expect(page.getByText('등록하는 중…')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '보내기 전 조치' })).toContainText('15번을 등록했어요')
})

test('AC-S05-12: 50번까지 등록한 뒤에도 15번 찾기, 판매 종료한 상품도 미리 보기', async ({ page }) => {
  await login(page)
  const date = uniqueDate()
  const b = await openNewBroadcast(page, { date, rehearsal: false })
  for (let no = 1; no <= 50; no += 1) {
    const r = await postJson(page, `/api/events`, { requestId: crypto.randomUUID(), type: 'product.register', b, no, name: `상품${String(no)}`, price: 1000 * no })
    expect(r.status).toBe(200)
  }
  await postJson(page, `/api/events`, { requestId: crypto.randomUUID(), type: 'product.close', b, no: 15 })
  await expect(boardItem(page, 50)).toBeVisible()
  const input = page.getByLabel('빠른 입력')
  await input.fill('15')
  const preview = page.getByRole('status', { name: '찾은 상품' })
  await expect(preview).toContainText('상품15')
  await expect(preview).toContainText('판매 종료')
  await input.press('Enter')
  await expect(page.getByRole('dialog', { name: '15번 자세히' })).toBeVisible()
})

