// 꾸밈말 붙은 품종 (실방송 금화다육 녹음 비교): 기본 품종 바로 앞 '창', 바로 뒤 '금'·'색금'(받아쓰기 오류 색급·세금·색감은 붙인 이름이 사전에 있을 때만)
import { describe, expect, it } from 'vitest'
import { extractVoice, prepareVoiceDictionary, readSegments } from '../src/index.ts'

const DICT = prepareVoiceDictionary()
const picks = (text: string) => readSegments(text, { dictionary: DICT, final: true, maxNumber: 999 }).picks.map((p) => [p.no, p.price, p.name])
const SMALL = ['버건디', '청개구리', '립스틱', '립스틱색금', '몰디브', '라울', '녹금']
const nameOf = (text: string) => extractVoice(text, { dictionary: SMALL }).name

describe('실방송 금화다육 — 기본 사전', () => {
  it.each([
    ['창 버건디에요 창 버건디인데 8만 원 15번', [[15, 80_000, '창버건디']]],
    ['256번 청개구리 금이래요 5만 원', [[256, 50_000, '청개구리금']]],
    ['청개구리 금이래요 청개구리 금입니다 256번 5만 원', [[256, 50_000, '청개구리금']]],
    ['329번 립스틱 색급 5만 원', [[329, 50_000, '립스틱색금']]],
    ['329번 립스틱 세금 5만 원', [[329, 50_000, '립스틱색금']]],
    ['329번 자 립스틱 색감 5만 원', [[329, 50_000, '립스틱색금']]],
  ])('%s', (text, expected) => {
    expect(picks(text)).toEqual(expected)
  })
  it("'색감이'는 빛깔 이야기 — 립스틱 그대로", () => {
    expect(picks('329번 립스틱 색감이 예쁘네요 5만 원')).toEqual([[329, 50_000, '립스틱']])
  })
  // 기본 사전엔 라울금·립스틱금·빅뱅금이 따로 있다 — 띄어 쓴 '금이'의 조사를 떼고 이어 맞추면 그 이름이 되던 것(R-17 5)
  it.each([
    ['15번 라울 금이 선명하게 나왔어요 5만 원', '라울'],
    ['15번 라울 금은 다 있어요 5만 원', '라울'],
    ['15번 라울 금을 보세요 5만 원', '라울'],
    ['15번 라울 금도 예뻐요 5만 원', '라울'],
    ['15번 립스틱 금이 선명해요 5만 원', '립스틱'],
    ['15번 빅뱅 금도 예뻐요 5만 원', '빅뱅'],
  ])("무늬 이야기 '%s' → %s (사전의 …금 이름으로 맞추지 않음)", (text, name) => {
    expect(picks(text)).toEqual([[15, 50_000, name]])
  })
  it.each([
    ['15번 라울금이 선명하게 나왔어요 5만 원', '라울금'],
    ['15번 라울금은 5만 원', '라울금'],
    ['15번 라울 금 5만 원', '라울금'],
    ['15번 라울 금이에요 5만 원', '라울금'],
    ['15번 빅뱅 금이래요 5만 원', '빅뱅금'],
  ])("붙여 쓴 이름·이름을 말하는 꼴 '%s' → %s (그대로)", (text, name) => {
    expect(picks(text)).toEqual([[15, 50_000, name]])
  })
})

describe('사전에 없는 붙인 이름', () => {
  it("앞 '창' (띄어 써도·붙여 써도)", () => {
    expect(nameOf('15번 창 버건디 8만 원')).toBe('창버건디')
    expect(nameOf('15번 창버건디 8만 원')).toBe('창버건디')
    expect(nameOf('15번 창 버건디에요 8만 원')).toBe('창버건디')
  })
  it("뒤 '금'·'색금' (띄어 써도·붙여 써도)", () => {
    expect(nameOf('256번 청개구리 금입니다 5만 원')).toBe('청개구리금')
    expect(nameOf('256번 청개구리금이에요 5만 원')).toBe('청개구리금')
    expect(nameOf('17번 몰디브 색금 5만 원')).toBe('몰디브색금')
    expect(nameOf('15번 창 버건디 금 8만 원')).toBe('창버건디금')
  })
  it('받아쓰기 오류 모양(색급·세금·색감)은 붙인 이름이 사전에 있을 때만', () => {
    expect(nameOf('329번 립스틱 색감 5만 원')).toBe('립스틱색금')
    expect(nameOf('17번 몰디브 색급 5만 원')).toBe('몰디브')
    expect(nameOf('17번 몰디브 세금 5만 원')).toBe('몰디브')
    expect(nameOf('17번 몰디브 색감 5만 원')).toBe('몰디브')
  })
  it('번호·가격은 그대로', () => {
    expect(extractVoice('256번 청개구리 금입니다 5만 원', { dictionary: SMALL })).toEqual({ no: 256, name: '청개구리금', price: 50_000, confidence: 'HIGH' })
    expect(extractVoice('창 버건디 8만 원 15번', { dictionary: SMALL })).toEqual({ no: 15, name: '창버건디', price: 80_000, confidence: 'HIGH' })
  })
})

describe('품종 바로 옆이 아니면 붙이지 않는다', () => {
  it.each([
    ['15번 라울 금이 선명하게 나왔어요 5만 원', '라울'], // 무늬 이야기 (조사 이·은·을·도)
    ['15번 라울 금은 다 있어요 5만 원', '라울'],
    ['15번 라울 자 금 5만 원', '라울'], // 군말이 끼면
    ['15번 라울이에요 금 5만 원', '라울'], // 품종 토큰에 말끝이 붙고 끝나면
    ['15번 버건디 8만 원 금이에요', '버건디'], // 가격이 끼면
    ['창 15번 버건디 8만 원', '버건디'], // 번호가 끼면
    ['15번 창가에 버건디 8만 원', '버건디'], // '창'이 따로 선 토큰이 아니면
    ['15번 녹금 금 5만 원', '녹금'], // 이미 '금'으로 끝나는 이름
    ['15번 창 버건디 버건디 금 8만 원', '버건디'], // 붙인 이름이 둘로 갈리면
    ['15번 라울 버건디 금 8만 원', null], // 두 이름이 갈려 비운 것은 그대로
    ['15번 방금 지금 8만 원', null], // 사전 이름이 아닌 앞 글 + 금
  ] as const)('%s → %s', (text, name) => {
    expect(nameOf(text)).toBe(name)
  })
})
